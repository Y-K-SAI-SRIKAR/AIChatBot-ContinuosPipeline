# 5. Model Metadata Contract
# =====================================================================

class ModelMetadata(BaseModel):
    """Metadata specification for versioned BERT intent classification models."""
    model_config = ConfigDict(extra="ignore")

    model_version: str = Field(
        ...,
        description="Semantic model version (e.g. 'v0.1.0-baseline', 'v0.2.0-candidate')."
    )
    model_name: str = Field(
        default="bert-intent-classifier",
        description="Model identifier name."
    )
    artifact_location: str = Field(
        ...,
        description="Relative or absolute path/URI to the model weights and tokenizer."
    )
    dvc_revision: Optional[str] = Field(
        default=None,
        description="DVC or git commit hash representing the dataset snapshot used for training."
    )
    dataset_version: str = Field(
        default="ChatBot-PipeLine/data/raw/Intent.json",
        description="Path or identifier of the source dataset."
    )
    num_classes: int = Field(
        default=22,
        ge=1,
        description="Number of target intent classes (22 in Intent.json)."
    )
    evaluation_metrics: Dict[str, float] = Field(
        default_factory=dict,
        description="Evaluation metrics dictionary (e.g. macro_f1, accuracy, latency_ms)."
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC timestamp of model artifact creation."
    )
    promotion_status: PromotionStatus = Field(
        default=PromotionStatus.CANDIDATE,
        description="Promotion lifecycle status ('candidate', 'production', 'archived', 'rejected')."
    )
    notes: Optional[str] = Field(
        default=None,
        description="Optional human-readable notes about this model checkpoint."
    )


# =====================================================================
# 6. Prompt Metadata Contract
# =====================================================================

class PromptMetadata(BaseModel):
    """Metadata specification for versioned Google ADK agent system instructions."""
    model_config = ConfigDict(extra="ignore")

    prompt_version: str = Field(
        ...,
        description="Semantic prompt version (e.g. 'v1.0.0', 'v1.1.0-candidate')."
    )
    instruction_path: str = Field(
        ...,
        description="Relative or absolute path to the instruction text file."
    )
    associated_adk_model: str = Field(
        default="gemini-3-flash-preview",
        description="Google ADK / Gemini model associated with this prompt."
    )
    associated_classifier_version: Optional[str] = Field(
        default=None,
        description="Compatible intent classifier version, if paired."
    )
    evaluation_status: PromptEvaluationStatus = Field(
        default=PromptEvaluationStatus.PRODUCTION,
        description="Evaluation status ('baseline', 'candidate', 'production', 'rejected')."
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC timestamp of prompt creation."
    )
    description: Optional[str] = Field(
        default=None,
        description="Summary of purpose or changes in this instruction version."
    )
    evaluation_metrics: Dict[str, float] = Field(
        default_factory=dict,
        description="Prompt benchmark evaluation scores, if evaluated."
    )

