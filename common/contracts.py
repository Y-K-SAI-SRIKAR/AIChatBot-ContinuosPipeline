# 3. Feedback Request Contract
# =====================================================================

class FeedbackRequest(BaseModel):
    """Incoming user feedback contract on a specific chat turn."""
    model_config = ConfigDict(extra="ignore")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Correlation ID of the chat turn being rated."
    )
    rating: FeedbackRating = Field(
        ...,
        description="User rating sentiment ('positive' or 'negative')."
    )
    corrected_intent: Optional[str] = Field(
        default=None,
        description="Optional user or supervisor provided ground-truth intent class."
    )
    corrected_response: Optional[str] = Field(
        default=None,
        description="Optional user or supervisor provided ideal response."
    )
    textual_feedback: Optional[str] = Field(
        default=None,
        description="Optional qualitative comment or notes on the chatbot behavior."
    )

    @field_validator("rating", mode="before")
    @classmethod
    def normalize_rating(cls, v: Any) -> FeedbackRating:
        return FeedbackRating.from_value(v)

    @field_validator("request_id")
    @classmethod
    def validate_req_id(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("request_id must not be empty.")
        return v.strip()


# =====================================================================
# 4. Feedback Record Contract (Persistence & Retraining Gate)
# =====================================================================

class FeedbackRecord(BaseModel):
    """
    Persisted feedback record used by continuous learning and drift pipelines.
    
    CRITICAL RULE:
    Negative feedback alone is NOT an eligible supervised training label.
    Only records with a verified corrected_intent are marked training_eligibility=True.
    """
    model_config = ConfigDict(extra="ignore")

    record_id: str = Field(
        default_factory=lambda: f"fbr_{uuid.uuid4().hex[:12]}",
        description="Globally unique, immutable ID for this feedback record."
    )
    request_id: str = Field(
        ...,
        description="Original chat request correlation ID."
    )
    message: str = Field(
        ...,
        description="User message that triggered the chatbot turn."
    )
    predicted_intent: Optional[str] = Field(
        default=None,
        description="Intent that was predicted by BERT during inference."
    )
    rating: FeedbackRating = Field(
        ...,
        description="User rating sentiment ('positive' or 'negative')."
    )
    corrected_intent: Optional[str] = Field(
        default=None,
        description="Explicitly verified ground-truth intent label, if provided."
    )
    corrected_response: Optional[str] = Field(
        default=None,
        description="Explicitly corrected chatbot response text, if provided."
    )
    textual_feedback: Optional[str] = Field(
        default=None,
        description="Qualitative user feedback notes."
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC timestamp of when the feedback was recorded (ISO-8601)."
    )
    model_version: str = Field(
        ...,
        description="Model version in production when this feedback was recorded."
    )
    prompt_version: str = Field(
        ...,
        description="Prompt version in production when this feedback was recorded."
    )
    training_eligibility: bool = Field(
        default=False,
        description="Whether this sample is verified and eligible for supervised intent retraining."
    )
    eligibility_reason: str = Field(
        default="",
        description="Explanation for why this sample is or is not eligible for retraining."
    )

    @field_validator("rating", mode="before")
    @classmethod
    def normalize_rating(cls, v: Any) -> FeedbackRating:
        return FeedbackRating.from_value(v)

    @model_validator(mode="after")
    def evaluate_training_eligibility(self) -> "FeedbackRecord":
        """
        Enforce the architectural principle:
        Negative feedback alone does NOT indicate the true label.
        Only explicit corrected_intent makes a sample eligible for BERT retraining.
        """
        if self.corrected_intent and self.corrected_intent.strip():
            self.training_eligibility = True
            self.eligibility_reason = (
                f"Eligible: Ground-truth corrected_intent '{self.corrected_intent.strip()}' provided."
            )
        elif self.rating == FeedbackRating.NEGATIVE:
            self.training_eligibility = False
            self.eligibility_reason = (
                "Ineligible: Negative rating without ground-truth corrected_intent. "
                "Preserved for drift and quality monitoring only."
            )
        else:
            self.training_eligibility = False
            self.eligibility_reason = (
                "Ineligible: Positive rating without ground-truth label change."
            )
        return self


