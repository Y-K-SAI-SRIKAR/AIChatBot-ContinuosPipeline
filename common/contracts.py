"""
Minimal Shared Contracts and Schemas for AI ChatBot Continuous Learning Pipeline.

This module defines the typed Pydantic data contracts for:
1. ChatRequest (message, conversation_id, auto-generated request_id)
2. ChatResponse (request_id, response, predicted_intent, intent_confidence, model_version, prompt_version, latency_ms)
3. FeedbackRequest (request_id, rating, optional corrected_intent, optional corrected_response, optional textual_feedback)
4. FeedbackRecord (stable record_id, message, predicted_intent, rating, corrected_intent, timestamp, versions, training_eligibility)
5. ModelMetadata (model_version, artifact_location, dvc_revision, evaluation_metrics, timestamp, promotion_status)
6. PromptMetadata (prompt_version, instruction_path, associated_model, evaluation_status)

CRITICAL ARCHITECTURAL RULES ENFORCED:
- Negative feedback alone is NOT an eligible supervised training label.
- Only feedback with explicit, verified corrected_intent is flagged training_eligibility=True.
- Model and prompt versioning metadata is strictly tracked and never overwritten.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
import uuid

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class FeedbackRating(str, Enum):
    """Normalized feedback rating sentiment."""
    POSITIVE = "positive"
    NEGATIVE = "negative"

    @classmethod
    def from_value(cls, val: Any) -> "FeedbackRating":
        """Convert varied rating values (e.g. +1, -1, thumbs_up) to enum."""
        if isinstance(val, cls):
            return val
        s = str(val).strip().lower()
        if s in {"positive", "pos", "1", "+1", "thumbs_up", "up", "true"}:
            return cls.POSITIVE
        if s in {"negative", "neg", "-1", "thumbs_down", "down", "false"}:
            return cls.NEGATIVE
        raise ValueError(f"Invalid rating value: {val}. Expected 'positive' or 'negative'.")


class PromotionStatus(str, Enum):
    """Lifecycle status for trained model candidates."""
    CANDIDATE = "candidate"
    PRODUCTION = "production"
    ARCHIVED = "archived"
    REJECTED = "rejected"


class PromptEvaluationStatus(str, Enum):
    """Lifecycle and evaluation status for prompt instruction versions."""
    BASELINE = "baseline"
    CANDIDATE = "candidate"
    PRODUCTION = "production"
    REJECTED = "rejected"


# =====================================================================
# 1. Chat Request Contract
# =====================================================================

class ChatRequest(BaseModel):
    """Incoming user chat query contract."""
    model_config = ConfigDict(extra="ignore")

    message: str = Field(
        ...,
        min_length=1,
        description="Non-empty user input utterance."
    )
    conversation_id: Optional[str] = Field(
        default=None,
        description="Optional conversation/session identifier. Defaults to None."
    )
    request_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique request ID. Automatically generated if omitted."
    )

    @field_validator("message")
    @classmethod
    def validate_message_non_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("message must be a non-empty string.")
        return v.strip()

    @field_validator("request_id")
    @classmethod
    def validate_request_id(cls, v: Optional[str]) -> str:
        if not v or not str(v).strip():
            return str(uuid.uuid4())
        return str(v).strip()


# =====================================================================
# 2. Chat Response Contract
# =====================================================================

class ChatResponse(BaseModel):
    """Outgoing chat response contract returned by the API."""
    model_config = ConfigDict(populate_by_name=True, extra="ignore")

    request_id: str = Field(
        ...,
        description="Unique correlation ID matching the incoming chat request."
    )
    response: str = Field(
        ...,
        description="Text generated by the AI ChatBot Agent (Google ADK / Gemini)."
    )
    predicted_intent: Optional[str] = Field(
        default=None,
        description="Intent classified by the BERT intent classifier, if available."
    )
    intent_confidence: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Confidence score [0.0 - 1.0] of predicted_intent, if available."
    )
    model_version: str = Field(
        ...,
        description="Active intent classifier model version (e.g. 'v0.1.0-baseline')."
    )
    prompt_version: str = Field(
        ...,
        description="Active ADK system prompt instruction version (e.g. 'v1.0.0')."
    )
    latency_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Total end-to-end processing latency in milliseconds."
    )

    @property
    def reply(self) -> str:
        """Backward-compatible alias for existing code expecting 'reply'."""
        return self.response


